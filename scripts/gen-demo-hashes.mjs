// Maintainer tool: regenerates the demo data hashes in src/core/demoHashes.ts.
// Demo flags are generated at random and written ONLY to .secrets/demo-flags.txt (git-ignored),
// so no plaintext flag ever lands in the repository.
//
//   node scripts/gen-demo-hashes.mjs
//
// Demo passwords are read from DEMO_ADMIN_PASSWORD / DEMO_PLAYER_PASSWORD (defaults are the
// documented demo passwords in the README).
import { webcrypto as crypto } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";

const ITER = 150_000;
const enc = new TextEncoder();
const b64 = (u8) => Buffer.from(u8).toString("base64");

async function pbkdf2(secret, saltB64) {
  const key = await crypto.subtle.importKey("raw", enc.encode(secret), "PBKDF2", false, ["deriveBits"]);
  const bits = await crypto.subtle.deriveBits(
    { name: "PBKDF2", hash: "SHA-256", salt: Buffer.from(saltB64, "base64"), iterations: ITER },
    key,
    256,
  );
  return b64(new Uint8Array(bits));
}
const salt = () => b64(crypto.getRandomValues(new Uint8Array(16)));
const word = () => {
  const words = ["portal", "rivet", "ember", "shard", "vault", "orbit", "cinder", "lattice", "warden", "comet", "relay", "glyph", "fracture", "aegis", "nebula", "tether"];
  const r = crypto.getRandomValues(new Uint32Array(1))[0];
  return words[r % words.length];
};
const hex = (n) => Buffer.from(crypto.getRandomValues(new Uint8Array(n))).toString("hex");

const CHALLENGES = [
  ["c-skyline", false],
  ["c-channel9", false],
  ["c-sentry", false],
  ["c-ledger", false],
  ["c-echoes", false],
  ["c-paradox", false],
  ["c-cipher", true],
  ["c-lastlight", false],
];
const USERS = [
  "admin",
  "kira.valdez", "oren.patel", "mina.strand",
  "leo.achterberg", "sana.iqbal", "dev.morrow",
  "ayla.brooks", "jun.takeda", "felix.odum",
  "noor.haddad", "cal.reyes", "isla.fenwick",
];
const ADMIN_PW = process.env.DEMO_ADMIN_PASSWORD || "command-demo-2026";
const PLAYER_PW = process.env.DEMO_PLAYER_PASSWORD || "squad-demo-2026";

const flags = {};
const flagHashes = {};
for (const [id, cs] of CHALLENGES) {
  const flag = `DC{${word()}_${word()}_${hex(3)}}`;
  flags[id] = flag;
  const s = salt();
  const norm = cs ? flag : flag.toLowerCase();
  flagHashes[id] = { salt: s, hash: await pbkdf2("flag:" + norm, s) };
}
const pwHashes = {};
for (const u of USERS) {
  const s = salt();
  pwHashes[u] = { salt: s, hash: await pbkdf2("pw:" + (u === "admin" ? ADMIN_PW : PLAYER_PW), s) };
}

const ts = `// AUTO-GENERATED by scripts/gen-demo-hashes.mjs. Hashes only; no plaintext flags.
export const DEMO_FLAG_HASHES: Record<string, { salt: string; hash: string }> = ${JSON.stringify(flagHashes, null, 2)};

export const DEMO_PASSWORD_HASHES: Record<string, { salt: string; hash: string }> = ${JSON.stringify(pwHashes, null, 2)};
`;
writeFileSync(new URL("../src/core/demoHashes.ts", import.meta.url), ts);
mkdirSync(new URL("../.secrets/", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../.secrets/demo-flags.txt", import.meta.url),
  "Demo flags (do not commit)\n" + Object.entries(flags).map(([k, v]) => `${k}\t${v}`).join("\n") + "\n",
);
console.log("Wrote src/core/demoHashes.ts and .secrets/demo-flags.txt");
